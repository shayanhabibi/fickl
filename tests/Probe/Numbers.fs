module Numbers

open System
open Check

let run () =
    // int32 wraparound and shifts
    check "int.max+1" (fun () -> string (Int32.MaxValue + 1))
    check "int.min-1" (fun () -> string (Int32.MinValue - 1))
    check "int.mul" (fun () -> string (123456789 * 987654321))
    check "int.neg.min" (fun () -> string (-Int32.MinValue))
    check "int.abs.min" (fun () -> string (abs Int32.MinValue))
    check "int.div.min.-1" (fun () -> string (Int32.MinValue / -1))
    check "int.rem.neg" (fun () -> string (-7 % 3))
    check "int.div.neg" (fun () -> string (-7 / 2))
    check "int.div0" (fun () -> let z = 0 in string (1 / z))
    check "int.shl33" (fun () -> string (1 <<< 33))
    check "int.shl32" (fun () -> string (1 <<< 32))
    check "int.shr.neg" (fun () -> string (-16 >>> 2))
    check "int.shl.neg" (fun () -> string (1 <<< -1))
    check "uint.shr" (fun () -> string (0xFFFFFFFFu >>> 4))
    check "int64.shl65" (fun () -> string (1L <<< 65))
    check "int64.max+1" (fun () -> string (Int64.MaxValue + 1L))
    check "int64.mul" (fun () -> string (123456789123L * 987654321L))
    check "uint64.max" (fun () -> string UInt64.MaxValue)
    check "uint64.sub" (fun () -> string (0UL - 1UL))
    check "byte.wrap" (fun () -> string (255uy + 1uy))
    check "sbyte.wrap" (fun () -> string (127y + 1y))
    check "int16.wrap" (fun () -> string (32767s + 1s))
    check "uint16.wrap" (fun () -> string (0us - 1us))
    check "byte.of.int" (fun () -> string (byte 300))
    check "byte.of.neg" (fun () -> string (byte -1))
    check "sbyte.of.200" (fun () -> string (sbyte 200))
    check "int.of.float.big" (fun () -> string (int 3e10))
    check "int.of.float.neg" (fun () -> string (int -2.7))
    check "int.of.nan" (fun () -> string (int nan))
    check "int64.of.float" (fun () -> string (int64 1e19))
    check "uint.of.neg" (fun () -> string (uint32 -1))
    check "int.of.uint.max" (fun () -> string (int 0xFFFFFFFFu))
    check "int.of.int64" (fun () -> string (int 0x1_0000_0001L))
    check "char.of.int" (fun () -> string (int (char 65601)))
    check "checked.add" (fun () -> string (Checked.(+) Int32.MaxValue 1))
    check "checked.int" (fun () -> string (Checked.int 3e10))
    check "checked.byte" (fun () -> string (Checked.byte 256))
    // floats
    check "float.tostring.1e21" (fun () -> string 1e21)
    check "float.tostring.1e15" (fun () -> string 1e15)
    check "float.tostring.1e16" (fun () -> string 1e16)
    check "float.tostring.small" (fun () -> string 1e-5)
    check "float.tostring.0.1+0.2" (fun () -> string (0.1 + 0.2))
    check "float.tostring.negzero" (fun () -> string -0.0)
    check "float.tostring.nan" (fun () -> string nan)
    check "float.tostring.inf" (fun () -> string -infinity)
    check "float32.tostring" (fun () -> string 0.1f)
    check "float32.tostring.big" (fun () -> string 16777217.0f)
    check "float.F2" (fun () -> (2.345).ToString("F2"))
    check "float.F0.half" (fun () -> (2.5).ToString("F0"))
    check "float.N2" (fun () -> (1234567.891).ToString("N2"))
    check "float.E3" (fun () -> (12345.678).ToString("E3"))
    check "float.G4" (fun () -> (12345.678).ToString("G4"))
    check "float.P1" (fun () -> (0.1234).ToString("P1"))
    check "float.custom" (fun () -> (1234.5).ToString("#,##0.00"))
    check "int.X" (fun () -> (255).ToString("X4"))
    check "int.x.neg" (fun () -> (-1).ToString("x"))
    check "int.D5" (fun () -> (-42).ToString("D5"))
    check "int64.X.neg" (fun () -> (-1L).ToString("X"))
    check "byte.X" (fun () -> (255uy).ToString("X"))
    check "round.half.even" (fun () -> string (Math.Round 2.5))
    check "round.half.even3" (fun () -> string (Math.Round 3.5))
    check "round.neg" (fun () -> string (Math.Round -2.5))
    check "round.away" (fun () -> string (Math.Round(2.5, MidpointRounding.AwayFromZero)))
    check "round.digits" (fun () -> string (Math.Round(2.675, 2)))
    check "round.digits2" (fun () -> string (Math.Round(1.005, 2)))
    check "round.op" (fun () -> string (round 0.5))
    check "truncate" (fun () -> string (truncate -2.7))
    check "floor.neg" (fun () -> string (floor -0.5))
    check "ceil.neg" (fun () -> string (ceil -0.5))
    check "sign.negzero" (fun () -> string (sign -0.0))
    check "sign.nan" (fun () -> string (sign nan))
    check "pown" (fun () -> string (pown 2 31))
    check "pown.int64" (fun () -> string (pown 3L 40))
    check "pown.neg" (fun () -> string (pown 2.0 -2))
    check "float.mod" (fun () -> string (-5.5 % 2.0))
    check "float.compare.nan" (fun () -> string (compare nan 1.0))
    check "float.compare.nan.nan" (fun () -> string (compare nan nan))
    check "float.eq.nan" (fun () -> string (nan = nan))
    check "float.equals.nan" (fun () -> string (nan.Equals(nan)))
    check "max.nan" (fun () -> string (max nan 1.0))
    check "min.nan" (fun () -> string (min 1.0 nan))
    check "Math.Max.nan" (fun () -> string (Math.Max(1.0, nan)))
    check "list.max.nan" (fun () -> string (List.max [ 1.0; nan; 2.0 ]))
    check "list.sort.nan" (fun () -> String.Join(",", List.sort [ 3.0; nan; 1.0 ]))
    check "hash.negzero" (fun () -> string ((hash 0.0) = (hash -0.0)))
    check "eq.negzero" (fun () -> string (0.0 = -0.0))
    check "float32.precision" (fun () -> string (float32 0.1 = 0.1f))
    check "float32.arith" (fun () -> string (0.1f + 0.2f))
    check "float.of.float32" (fun () -> string (float 0.1f))
    // decimal
    check "decimal.add" (fun () -> string (0.1M + 0.2M))
    check "decimal.div" (fun () -> string (1M / 3M))
    check "decimal.trailing" (fun () -> string (1.10M))
    check "decimal.mul.scale" (fun () -> string (1.10M * 2.00M))
    check "decimal.round" (fun () -> string (Math.Round(2.5M)))
    check "decimal.round2" (fun () -> string (Math.Round(2.345M, 2)))
    check "decimal.max" (fun () -> string Decimal.MaxValue)
    check "decimal.overflow" (fun () -> string (Decimal.MaxValue + 1M))
    check "decimal.of.float" (fun () -> string (decimal 0.1))
    check "decimal.tostring.F" (fun () -> (1.5M).ToString("F3"))
    check "decimal.eq.scale" (fun () -> string (1.0M = 1.00M))
    check "decimal.hash.scale" (fun () -> string (hash 1.0M = hash 1.00M))
    check "decimal.int" (fun () -> string (int 2.9M))
    check "decimal.int.neg" (fun () -> string (int -2.9M))
    // parsing
    check "int.parse.space" (fun () -> string (Int32.Parse " 42 "))
    check "int.parse.plus" (fun () -> string (Int32.Parse "+42"))
    check "int.parse.float" (fun () -> string (Int32.Parse "4.2"))
    check "int.parse.overflow" (fun () -> string (Int32.Parse "2147483648"))
    check "int.parse.empty" (fun () -> string (Int32.Parse ""))
    check "int.parse.hex" (fun () -> string (Int32.Parse("ff", Globalization.NumberStyles.HexNumber)))
    check "int.tryparse.bad" (fun () -> string (Int32.TryParse "12a"))
    check "int.of.string.hex" (fun () -> string (int "0x1F"))
    check "int.of.string.bin" (fun () -> string (int "0b101"))
    check "int.of.string.oct" (fun () -> string (int "0o17"))
    check "int.of.string.space" (fun () -> string (int " 7"))
    check "byte.parse.256" (fun () -> string (Byte.Parse "256"))
    check "float.parse" (fun () -> string (Double.Parse "1e3"))
    check "float.parse.inf" (fun () -> string (Double.Parse "Infinity"))
    check "float.parse.comma" (fun () -> string (Double.Parse "1,000"))
    check "float.parse.bad" (fun () -> string (Double.Parse "abc"))
    check "float.of.string" (fun () -> string (float " 2.5 "))
    check "float.tryparse.hex" (fun () -> string (Double.TryParse "0x10"))
    check "int64.parse.max" (fun () -> string (Int64.Parse "9223372036854775807"))
    check "uint64.parse" (fun () -> string (UInt64.Parse "18446744073709551615"))
    check "decimal.parse" (fun () -> string (Decimal.Parse "1.2300"))
    check "bigint.parse" (fun () -> string (Numerics.BigInteger.Parse "-123456789012345678901234567890"))
    check "bigint.pow" (fun () -> string (Numerics.BigInteger.Pow(2I, 100)))
    check "bigint.div.neg" (fun () -> string (-7I / 2I))
    check "bigint.rem.neg" (fun () -> string (-7I % 2I))
    check "bigint.of.float" (fun () -> string (bigint 1e20))
    check "convert.toint32.round" (fun () -> string (Convert.ToInt32 2.5))
    check "convert.toint32.round3" (fun () -> string (Convert.ToInt32 3.5))
    check "convert.toint32.str" (fun () -> string (Convert.ToInt32 "-12"))
    check "convert.tobyte.over" (fun () -> string (Convert.ToByte 256))
    check "convert.tostring.base2" (fun () -> Convert.ToString(10, 2))
    check "convert.tostring.base16.neg" (fun () -> Convert.ToString(-1, 16))
    check "convert.toint32.base" (fun () -> string (Convert.ToInt32("ff", 16)))
    check "bitconverter" (fun () -> String.Join(",", BitConverter.GetBytes 258))
    check "int.bitnot" (fun () -> string (~~~0))
    check "uint.bitnot" (fun () -> string (~~~0u))
    check "byte.bitnot" (fun () -> let mutable z = 0uy in string (~~~z))
    check "sbyte.bitnot" (fun () -> let mutable z = 0y in string (~~~z))
    check "uint16.bitnot" (fun () -> let mutable z = 0us in string (~~~z))
    check "int64.bitand" (fun () -> string (0x1_0000_0000L &&& 0x1_0000_0000L))
    check "enum.tostring" (fun () -> string DayOfWeek.Monday)
    check "enum.int" (fun () -> string (int DayOfWeek.Friday))
    check "enum.flags" (fun () -> string (IO.FileAttributes.ReadOnly ||| IO.FileAttributes.Hidden))
    check "enum.undefined" (fun () -> string (enum<DayOfWeek> 9))
